-- =====================================================================
-- V2.3.22 : company 에 위도·경도 추가                            [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   기업 설정 > 기본 정보 탭이 회사 위치를 지도로 보여준다. 지금은 address 문자열만
--   있어서 화면이 뜰 때마다 지오코딩을 한 번 더 해야 하고, 같은 주소가 SDK 버전에
--   따라 다른 좌표로 찍힌다. 사용자가 지도에서 고른 그 지점을 그대로 저장한다.
--
-- 설계 메모:
--   · DOUBLE 이다. 애플리케이션이 Double 로 다루므로 DECIMAL(BigDecimal) 과 타입을
--     맞추면 매핑에서 변환이 한 겹 더 생긴다. 위경도는 정확한 십진 표현이 필요한
--     금액류가 아니라 측정값이라 이진 부동소수로 충분하다(소수 7자리 ≈ 1cm).
--   · NULL 을 허용한다. address 와 같은 이유다(V2.3.20) — 지도 SDK 가 뜨지 않는
--     환경에서는 좌표 없이 주소만 채울 수 있어야 한다. 둘 중 하나만 있는 상태도
--     정상이라 NOT NULL 이나 CHECK 로 짝을 강제하지 않는다.
--   · 값 범위 검사(위도 ±90 · 경도 ±180)는 요청 DTO 에서 한다. DB CHECK 로 막으면
--     범위를 벗어난 입력이 400 이 아니라 500 으로 나간다.
-- =====================================================================

ALTER TABLE `company`
    ADD COLUMN `latitude`  DOUBLE NULL COMMENT '회사 위치 위도 — 기업 설정 지도에서 고른 지점(선택)' AFTER `address`,
    ADD COLUMN `longitude` DOUBLE NULL COMMENT '회사 위치 경도 — 기업 설정 지도에서 고른 지점(선택)' AFTER `latitude`;
