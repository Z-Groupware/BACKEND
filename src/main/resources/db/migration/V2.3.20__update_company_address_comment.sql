-- =====================================================================
-- V2.3.20 : company.address 컬럼 주석 정정 — 등록 신청에서도 받는다  [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   V2.2.8은 이 컬럼에 '주소 — 등록 폼에 없고 기업 설정에서 채운다'는 주석을
--   달았다. 그때는 사실이었지만 2026-08-10에 뒤집혔다. 기업 등록 신청 화면이
--   카카오맵으로 회사 위치를 고르는데, 기업 설정(PATCH /api/companies/me)은
--   오너 로그인이 필요해 온보딩 4단계를 마치기 전에는 열리지 않는다. 그
--   사이 회사 주소를 아무도 모르는 구간이 생겨, 신청 시점에 받기로 했다.
--
--   V2.2.8을 고쳐 주석만 바꾸지 않는다 — 이미 적용된 마이그레이션의 내용을
--   바꾸면 Flyway 체크섬 검증이 깨져 기존 환경이 전부 기동에 실패한다.
--
-- 설계 메모:
--   · 타입·NULL 허용·기본값을 그대로 두고 COMMENT만 바꾸는 문장이다.
--     데이터는 건드리지 않으므로 되돌릴 것도 없다.
--   · 주소는 여전히 선택이라 NULL을 유지한다. 지도 SDK가 뜨지 않는 환경에서는
--     사용자가 주소 없이 신청할 수 있어야 한다.
-- =====================================================================

ALTER TABLE `company`
    MODIFY COLUMN `address` VARCHAR(255) NULL COMMENT '회사 주소 — 등록 신청(선택) 또는 기업 설정에서 채운다';
