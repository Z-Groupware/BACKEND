-- =====================================================================
-- V5.23 : transcript_chunk — STT 화자 분리 라벨
-- ---------------------------------------------------------------------
-- 2026-08-17 설계 변경. AWS Transcribe 의 화자 분리(ShowSpeakerLabels)를 켜고, 그 라벨을
-- 정본에 남긴다. **화자 판정의 주 경로가 rms 에서 라벨로 바뀐다.**
--
-- ── 왜 바꾸나 — rms 경로는 구조적으로 항상 기권한다 ──────────────────
-- V5.3 이 깔아 둔 판정은 "참석자 각자 브라우저가 person_id 와 rms 를 보내니 L1 이 시간창을
-- 맞춰 화자를 정한다"였다. 그런데 그 뒤 녹음이 host 한 대로 확정되면서 자막도 host 만
-- 보내게 됐고(CaptionController host-only), L1 의 「전원 자막」 게이트는 참석자가 2명
-- 이상인 모든 회의에서 거짓이 된다. 즉 **모든 발화의 화자가 NULL 이었다.**
--
-- 그 게이트를 완화하면 안 된다 — host 만 자막을 켠 회의에서 남의 발화가 전부 host 것이
-- 된다. 셋 중 하나를 바꿔야 하고, 바꿀 수 있는 것은 diarization 결정 하나뿐이다
-- (참석자 자막 확장은 캡처 워크플로우가 막았다).
--
-- ── 라벨은 사람이 아니다. 그래서 컬럼을 따로 둔다 ────────────────────
-- Transcribe 가 주는 것은 `spk_0`·`spk_1` 이고 그것이 누구인지는 말하지 않는다. 사람으로
-- 바꾸는 것은 별도 판정이다(SpeakerLabelAnchorResolver). 두 값을 한 컬럼에 담으면
-- "구분은 됐지만 누구인지 모른다"와 "판정을 포기했다"가 같은 모양이 되는데, 그 둘은
-- 완전히 다른 상태다 — 앞은 닻 하나만 찾으면 회의 전체가 풀리고 뒤는 아무 근거도 없다.
--
-- 라벨이 있는데 speaker_member_id 가 NULL 인 행이 **정상적으로 존재한다.** 그 라벨에
-- 아직 닻을 못 내린 것이고, 같은 회의 다른 구간에서 닻이 잡히면 다음 실행에 채워진다.
--
-- ── 블록 스코프 값이다 ──────────────────────────────────────────────
-- ⚠ Transcribe 는 **잡 하나(=블록 하나) 안에서만** 라벨을 일관되게 준다. 블록 2 의
-- `spk_0` 과 블록 3 의 `spk_0` 은 같은 사람이라는 보장이 없다. 그래서 저장 값에 블록을
-- 붙여 `3:spk_0` 형태로 넣는다 — stt_block_seq 와 함께 봐야 뜻이 정해지는 값이고,
-- 라벨만 보고 회의 전체를 묶으면 블록 경계에서 화자가 서로 뒤바뀐다.
-- 길이 16 은 `999:spk_29`(최대 30 화자 · 블록 세 자리)를 담고도 남는다.
--
-- ── speaker_source 에 값을 하나 더한다 ──────────────────────────────
-- DIARIZATION_ANCHORED = 라벨로 구분하고, 그 라벨을 사람에 닻 내려 확정했다.
-- 기존 두 값(SELF_STREAM · ELIMINATION)은 지우지 않는다 — 이 변경 전에 판정된 행이 그
-- 값을 들고 있고, 라벨이 없는 경로(스텁 · whisper · 이 마이그레이션 이전 블록)에서는
-- 여전히 rms 경로가 돈다. 두 경로는 **라벨의 유무로 배타적이라** 한 발화를 두고 다투지
-- 않는다(SpeakerAttributionResolver 주석).
--
-- 판정 포기는 그대로 speaker_member_id · speaker_source 가 **함께 NULL** 인 것으로
-- 표현한다(V5.3 규칙). 라벨은 그 규칙 밖이다 — 판정이 아니라 입력이다.
-- =====================================================================

ALTER TABLE `transcript_chunk`
    ADD COLUMN `speaker_label` VARCHAR(16) NULL
        COMMENT 'STT 화자 분리 라벨. `{stt_block_seq}:spk_N` — 블록 안에서만 일관되다. 사람 아님. NULL=분리 없이 인식된 발화'
        AFTER `speaker_source`;

ALTER TABLE `transcript_chunk`
    MODIFY COLUMN `speaker_source` ENUM('SELF_STREAM', 'ELIMINATION', 'DIARIZATION_ANCHORED') NULL
        COMMENT '판정 근거. SELF_STREAM=본인 스트림 rms 최대 / ELIMINATION=소거법 / DIARIZATION_ANCHORED=화자 분리 라벨을 사람에 닻 내림 / NULL=미판정';
