-- =====================================================================
-- V2.2.1 : member 에 어드민 겸직 플래그(is_admin) 추가        [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   확정된 권한 모델은 "어드민 = 오너/리더/멤버가 추가로 겸직하는 부가 권한"이다.
--   그런데 member.role 이 단일 ENUM('OWNER','ADMIN','LEADER','MEMBER') 이라
--   '리더 + 어드민' 같은 조합을 표현할 수 없다.
--
--   따라서 기본 역할은 role 이 그대로 담고, 어드민 겸직 여부만 별도 플래그로 뗀다.
--     실제 권한 = role(기본) + is_admin 이면 관리 4종 추가
--     (계정 발급 · 직급 권한 변경 · 회의실 관리 · 구독 결제 보기)
--
-- 주의:
--   role ENUM 에서 'ADMIN' 값을 제거하는 것은 이 파일에서 하지 않는다.
--   ENUM 변경은 별개의 DDL 이고, MySQL 은 DDL 롤백이 불가능하므로
--   운영 규칙 8-1(1파일 1논리변경)에 따라 후속 마이그레이션으로 분리한다.
-- =====================================================================

ALTER TABLE `member`
    ADD COLUMN `is_admin` BOOLEAN NOT NULL DEFAULT FALSE
    COMMENT '어드민 겸직 여부. 1이면 기본 역할에 관리 권한 4종이 추가된다'
    AFTER `role`;

-- 기존에 role='ADMIN' 으로 저장된 행이 있다면 겸직 플래그로 옮긴다.
-- (role 값 자체는 건드리지 않는다. 기본 역할을 임의로 추정하지 않기 위함이며,
--  정리는 role ENUM 정비 마이그레이션에서 함께 다룬다.)
UPDATE `member` SET `is_admin` = TRUE WHERE `role` = 'ADMIN';
