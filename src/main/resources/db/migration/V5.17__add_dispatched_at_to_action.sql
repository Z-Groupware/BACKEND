-- =====================================================================
-- V5.17 : action.dispatched_at — 분배 확정 시각 (RVW-05)
-- ---------------------------------------------------------------------
-- ⚠️ 공용 테이블(action) 변경이다. DB_MIGRATION_RULES 7번에 따라 팀 채널
--    사전 공유가 필요하다. 컬럼 추가(ADD COLUMN NULL)라 기존 행·쿼리에는
--    영향이 없지만, 규칙은 "영향이 없어 보여도 먼저 알린다"이다.
--
-- 왜 confirmed_at 으로 안 되나 — 그 컬럼은 이미 다른 순간을 가리킨다.
-- RVW-02 가 액션 하나를 사람이 확정·반려할 때 찍는 값이고(applyHumanReview),
-- 반려하면 지워진다. RVW-05 는 그와 다른 순간이다 — **회의의 검토를 끝내고
-- 액션 묶음을 보드로 내보낸 시각**이며, 한 번 나가면 되돌리지 않는다.
--
-- 두 값이 실제로 갈리는 예: 담당자를 고쳐 확정(confirmed_at 찍힘)했지만 아직
-- 분배 확정 버튼을 누르지 않은 액션. 그 액션은 보드에 없어야 하고, 그 사실을
-- 말해주는 값이 dispatched_at IS NULL 이다. 하나로 합치면 "확정했는데 아직
-- 안 나간 상태"를 표현할 방법이 사라진다.
--
-- RVW-01 이 이 값을 이미 응답에 내려주고 있다(항상 null 이었다). 화면의
-- "확정 전 검토 가능"이 그 null 의 뜻이다.
--
-- 인덱스를 걸지 않는다. 조회는 항상 회의 단위(source_meeting_id)로 좁힌 뒤
-- 이 값을 보므로 단독 인덱스가 탈 일이 없다. action 테이블의 인덱스 보강은
-- 별개 주제이고 그것도 사전 공유 대상이다.
-- =====================================================================

ALTER TABLE `action`
    ADD COLUMN `dispatched_at` DATETIME NULL
        COMMENT '분배 확정(RVW-05)으로 보드에 내보낸 시각. NULL이면 아직 아무 데도 가 있지 않다';
