-- =====================================================================
-- V4.4.1 : capture_upload_state에 마지막 STT 블록 끝 지점 추가 (김현지 레인 V4.x)
-- ---------------------------------------------------------------------
-- 10분/40청크 자동 블록 트리거(CAP-07 처리 정책)가 블록을 연달아 이어 붙이려면
-- "방금 만든 블록이 몇 ms에서 끝났는지"를 기억해야 다음 블록이 그 지점부터 시작할 수 있다.
-- blocks_formed(V4.1)가 "몇 개 만들었는지"라면, 이 컬럼은 "어디까지 만들었는지"다.
--
-- 기존 행이 없다는 전제로(이 기능이 지금까지 코드 자체가 없었음) NOT NULL DEFAULT 0으로 바로
-- 추가한다 — 나중에 채워야 할 기존 데이터가 없다.
-- =====================================================================

ALTER TABLE `capture_upload_state`
    ADD COLUMN `last_block_end_offset_ms` INT NOT NULL DEFAULT 0
        COMMENT '마지막으로 형성된 STT 블록의 끝 지점(ms). 다음 블록의 시작 지점 기준' AFTER `blocks_formed`;
