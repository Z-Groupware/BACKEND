-- ---------------------------------------------------------------------
-- 배경:
--   본부>팀 2계층 모델을 폐지한다(2026-08-07 결정). "부서 안에 역할이
--   있다"(개발팀 > 프론트/백엔드)로 확정됐고, 역할은 team이 아니라
--   role 테이블(V2.3.4에서 sub_team을 rename)이 이미 담당한다.
--   team은 이제 계층이 없는 평평한 목록이라 V2.3.13의 "부모 스코프 유일성"이
--   의미를 잃는다 — 회사 전체에서 이름이 유일해야 한다.
--
-- 순서 주의: name_scope_parent_id는 parent_team_id를 참조하는 생성 컬럼이라,
--   parent_team_id 컬럼 자체를 지우기 전에(V2.3.17) 먼저 지워야 한다.
-- =====================================================================

ALTER TABLE `team`
    DROP INDEX `UK_TEAM_COMPANY_PARENT_NAME`,
    DROP COLUMN `name_scope_parent_id`,
    ADD CONSTRAINT `UK_TEAM_COMPANY_NAME` UNIQUE (`company_id`, `name`);
