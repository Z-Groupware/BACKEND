-- =====================================================================
-- V5.22 : meeting_assignment_tuple — 담당자를 코드가 이었는지
-- ---------------------------------------------------------------------
-- L4 가 담당자를 비워 둔 tuple 을, 근거 발화 주변에서 글자 하나 차이인 참석자와 코드가
-- 이어 준 경우다(NearNameAssigneeResolver). 그 사실을 값으로 남긴다.
--
-- ── 왜 컬럼을 하나 더 두나 ────────────────────────────────────────────
-- assignee_source 로는 구분할 수 없다. 코드가 이어도 그 값은 EXPLICIT_CALL 그대로다 —
-- 모델이 "명시적 호명이다"라고 판정한 것은 사실이고, 바뀐 것은 그 이름을 명단에 이었다는
-- 점뿐이다. source 에 새 값을 만들면 Python 이 보내지 않는 값이 전송 계약에 생긴다
-- (AssigneeSource 주석: 전송 표현과 도메인 표현을 섞지 않는다).
--
-- 남기지 않으면 되짚을 수 없는 것이 둘이다.
--   1) 코드가 이은 배정의 오답률. 2026-08-14 실측은 회의 1 건 · 배정 4 건 규모라
--      "오답 0 건"의 눈금이 굵다. 허용 편집거리를 두 글자로 넓힐지는 실제 회의에서
--      이 컬럼으로 센 오답률이 있어야 정할 수 있다.
--   2) 담당자 정확도에서 모델의 몫과 코드의 몫. 뭉치면 프롬프트를 고쳤을 때 나아진 것이
--      모델인지 이 코드인지 모른다.
--
-- ── NULL 의 뜻 ────────────────────────────────────────────────────────
-- V5.13 verify_agree · V5.14 gate_* 와 같은 규칙이다.
--   NULL   근접 매칭이 이 행을 보지 않았다(이 마이그레이션 이전에 저장된 행)
--   FALSE  봤고, 잇지 않았다 — 담당자를 모델이 정했거나 조건을 못 채워 기권했다
--   TRUE   코드가 이었다
-- FALSE 와 NULL 을 뭉치면 이 코드 이전 회의가 전부 "코드가 안 이은 회의"로 보여
-- 오답률 분모가 틀어진다. 그래서 DEFAULT 를 두지 않는다.
--
-- ⚠ TRUE 인 행은 자동확정되지 않는다
-- L7 이 이 값을 보고 자동확정에서 뺀다(AutoConfirmGate). 게이트는 조이는 방향으로만
-- 더한다는 규칙 그대로다 — 코드가 이은 담당자는 검토 화면의 「AI 확인 필요」로 올라가고
-- 사람이 확인한다. 표본이 얇은 판정을 사람 눈 밖으로 내보내지 않는다.
-- =====================================================================

ALTER TABLE `meeting_assignment_tuple`
    ADD COLUMN `assignee_near_matched` BOOLEAN NULL
        COMMENT '담당자를 근접 매칭(코드)이 이었는가. NULL=미수행, FALSE=기권/모델 판정, TRUE=코드가 이음'
        AFTER `assignee_source`;
