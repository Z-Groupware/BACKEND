-- =====================================================================
-- V4.2.2 : recording 테이블에 stt_triggered 컬럼 추가 (김현지 V4.x 레인)
-- ---------------------------------------------------------------------
-- CAP-15 삭제 차단 판정("모든 stt_block.status=DONE")은 stt_block이 0건이면 공허참으로 통과한다.
-- 이게 "STT가 모두 끝남"인지 "STT가 아직 시작도 안 함"인지 recording만 봐서는 구분이 안 됐다 —
-- 등록 직후 ~ 첫 stt_block이 생기기 전 짧은 창구에서 confirm 없이도 삭제가 통과되는 구멍이 있었다
-- (CodeRabbit 리뷰로 확인, #11 PR).
--
-- 저장 직후 STT를 실제로 트리거하는 경로(현재 CAP-10 수동 업로드)는 이 값을 true로 등록해,
-- "트리거는 됐는데 아직 블록이 없음"을 미완료로 판정할 수 있게 한다.
-- =====================================================================

ALTER TABLE `recording`
    ADD COLUMN `stt_triggered` TINYINT(1) NOT NULL DEFAULT 0
    COMMENT 'STT 트리거 여부 — stt_block 0건이 미시작인지 완료인지 구분(CAP-15)'
    AFTER `duration_sec`;
