-- =====================================================================
-- V5.21 : meeting_vocabulary — 어휘 생성 추적 컬럼 셋 (CodeRabbit PR #353 지적)
-- ---------------------------------------------------------------------
-- V5.19 가 활성/대기 이름을 나눠 두면서 "승격은 후속"이라고 남겼다. 그 승격을 실제로
-- 만들면서 세 가지가 저장될 자리가 없다는 것이 드러났다.
--
-- ① stale_vocabulary_name — 승격으로 밀려난 이전 활성 리소스
--    승격되면 활성 칸이 새 이름으로 덮이고 이전 이름은 **호출자 손에만 남는다.** 그
--    자리에서 곧바로 지우면 두 가지가 깨진다:
--      · 삭제가 실패했을 때 다시 시도할 대상이 없다 — 이름이 사라져 영영 못 지운다.
--        V5.19 가 경고한 계정 상한 누수가 정확히 이 모양이다.
--      · **아직 도는 STT 잡이 그 이름을 참조할 수 있다.** 정리 경로는 "받아쓰기가 끝났나"를
--        보고 지우는데, 승격 경로만 그 검사를 건너뛰면 규칙이 두 갈래가 된다.
--    그래서 밀려난 이름을 여기 적어 두고, 정리 워커가 같은 검사를 지나 지운다.
--
-- ② pending_phrase_count — 대기 빌드의 단어 수
--    phrase_count 는 "마지막으로 성공한" 값이고 재생성 중에도 유지된다(V5.19). 그래서
--    승격 시점에 새 어휘의 단어 수를 알 방법이 없었다 — 제공자는 개수를 돌려주지 않는다.
--    그 값을 아는 유일한 시점이 **제출**이므로 거기서 적어 두고 승격이 옮긴다.
--    이 컬럼이 없으면 첫 생성은 0 으로 승격되고 재생성은 이전 개수로 갱신된다(둘 다 틀렸다).
--
-- ③ build_started_at — 제출 시각
--    제공자가 계속 PENDING 을 답하는 빌드가 있으면 그 회의는 영원히 "만드는 중"이고,
--    선점이 PENDING 을 막으므로 **사람이 다시 누를 수도 없다.** 얼마나 기다렸는지를
--    알아야 포기 시점을 정할 수 있다. created_at·updated_at 으로는 대신할 수 없다 —
--    created_at 은 행이 처음 생긴 시각이고(재생성이면 한참 전), updated_at 은
--    ON UPDATE 가 없어 움직이지 않는다.
-- =====================================================================

ALTER TABLE `meeting_vocabulary`
    ADD COLUMN `stale_vocabulary_name` VARCHAR(200) NULL
        COMMENT '승격으로 밀려난 이전 활성 리소스. 정리 워커가 받아쓰기 종료를 확인한 뒤 지운다',
    ADD COLUMN `pending_phrase_count`  INT          NULL
        COMMENT '대기 빌드의 단어 수. 제공자가 개수를 안 주므로 제출 시점에 적어 두고 승격이 옮긴다',
    ADD COLUMN `build_started_at`      DATETIME     NULL
        COMMENT '제공자에 접수한 시각. 응답 없이 오래 걸린 빌드를 포기하는 기준';

-- 정리 대상 조회가 활성 이름과 밀려난 이름 **양쪽**을 본다. V5.19 의
-- IX_MEETING_VOCABULARY_CLEANUP(deleted_at, status)는 활성 쪽만 받으므로,
-- 밀려난 이름이 남은 행을 찾는 조회를 위해 하나 더 둔다.
CREATE INDEX `IX_MEETING_VOCABULARY_STALE`
    ON `meeting_vocabulary` (`stale_vocabulary_name`);
