-- =====================================================================
-- V2.2.2 : role='ADMIN' 행을 MEMBER 로 정리                  [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   확정 권한 모델은 "어드민 = 기본 역할에 겸직하는 부가 권한"이다.
--   겸직 여부는 V2.2.1 이 추가한 member.is_admin 이 담고, role 은
--   OWNER / LEADER / MEMBER 세 값만 남긴다.
--
--   V2.2.1 은 role='ADMIN' 행의 is_admin 을 TRUE 로 올려두었지만
--   role 값 자체는 건드리지 않았다("기본 역할을 임의로 추정하지 않기 위함").
--   이제 그 정리를 한다 — 기본 역할을 알 수 없으므로 최소 권한인 MEMBER 로 내린다.
--
-- 주의:
--   ENUM 축소(V2.2.3)보다 반드시 먼저 실행돼야 한다. 제거될 값이 행에 남아 있으면
--   MySQL 이 MODIFY COLUMN 에서 Error 1265(Data truncated)로 실패한다.
--   그래서 데이터 정리와 ENUM 축소를 한 파일에 담지 않고 나눴다(운영 규칙 8-2).
--
--   권한이 필요한 사람은 is_admin=TRUE 로 관리 4종을 그대로 유지한다.
--   role 이 MEMBER 로 내려가도 관리 메뉴 접근은 잃지 않는다.
-- =====================================================================

UPDATE `member`
   SET `role` = 'MEMBER'
 WHERE `role` = 'ADMIN';
