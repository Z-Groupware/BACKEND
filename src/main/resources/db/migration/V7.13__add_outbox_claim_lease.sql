-- =====================================================================
-- V7.13 : token_usage_outbox — 릴레이 인스턴스 동시성 보호(리스 클레임)
-- ---------------------------------------------------------------------
-- 문제: 여러 앱 인스턴스가 동시에 PENDING 항목을 조회·처리하면 같은 항목을
-- 두 번 처리할 수 있다. 원장은 job_id 멱등이라 중복 과금은 막히지만, 같은
-- 항목을 여러 인스턴스가 경쟁하며 DB 에 불필요한 부하를 일으킨다.
--
-- 해법: claimed_until(리스 만료 시각). 릴레이가 항목을 가져가기 전에
-- claimed_until = now + 5분 을 조건부 UPDATE(atomic) 한다. 업데이트된 행이
-- 1이면 클레임 성공 → 처리 진행. 0이면 다른 인스턴스가 이미 가져감 → 건너뜀.
-- 클레임한 인스턴스가 crash 하면 만료 후 다른 인스턴스가 재획득 가능.
-- =====================================================================

ALTER TABLE token_usage_outbox
    ADD COLUMN claimed_until DATETIME(6) NULL
        COMMENT '릴레이 리스 만료 시각. 이 시각이 지나면 다른 인스턴스가 재획득 가능'
        AFTER next_attempt_at;
