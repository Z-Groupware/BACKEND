-- =====================================================================
-- V2.2.11 : status='ON_LEAVE' 행을 VACATION 으로 정리           [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   V2.2.10 이 목록에 VACATION 을 더했다. 같은 뜻의 값이 둘 공존하는 상태이므로
--   기존 행을 새 이름으로 옮긴다.
--
-- 선행:
--   V2.2.10 없이 이 파일을 먼저 돌리면 VACATION 이 유효한 값이 아니라 UPDATE 가
--   실패한다(strict mode) 또는 빈 문자열로 잘린다.
--
-- 후행:
--   V2.2.12 가 목록에서 ON_LEAVE 를 뺀다. 이 파일 없이 그것을 먼저 돌리면
--   Error 1265(Data truncated for column 'status')로 실패한다.
--   데이터 정리와 ENUM 축소를 한 파일에 담지 않는 이유다(운영 규칙 8-2,
--   V2.2.2 → V2.2.3 과 같은 구조).
--
-- 의미 변화는 없다:
--   ON_LEAVE 와 VACATION 은 같은 상태(휴직)의 다른 이름이다. 이 UPDATE 로
--   사람의 상태가 바뀌지 않는다.
-- =====================================================================

UPDATE `member`
   SET `status` = 'VACATION'
 WHERE `status` = 'ON_LEAVE';
