-- =====================================================================
-- V2.3.14 : position 에 설명(description) 추가                [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   API_SPEC.md §6-6 직급 목록 응답은 `description`(권한 요약 문구, 예:
--   "회의 참석, 액션 관리, 개인 인수인계")을 필수 필드로 요구한다. 기존
--   {name, authority} 두 컬럼에는 이 값을 담을 곳이 없었다.
--
-- 설계 메모:
--   · NOT NULL DEFAULT '' — 기존 행(V1 baseline 이후 만들어졌을 수 있는
--     직급)이 있어도 이 마이그레이션이 실패하지 않는다. 빈 문자열은
--     "아직 설명을 안 채운 직급"으로 자연스럽게 읽힌다.
-- =====================================================================

ALTER TABLE `position`
    ADD COLUMN `description` VARCHAR(200) NOT NULL DEFAULT ''
        COMMENT '직급 권한 요약 (기업 설정 · 온보딩 화면 표시용)' AFTER `authority`;
