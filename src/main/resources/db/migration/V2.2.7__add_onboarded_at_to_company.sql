-- =====================================================================
-- V2.2.7 : company 에 온보딩 완료 시각(onboarded_at) 추가       [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   온보딩(부서·직급·사원 초대)은 한 번만 도는 흐름이다. [완료] 한 번으로
--   조직이 확정되고 초대 메일이 나가므로, 두 번 부르면 조직이 중복 생성되고
--   같은 사람에게 비밀번호 메일이 두 번 간다.
--
--   프론트는 sessionStorage 로만 막고 있어 새 탭·다른 기기에서는 그대로 열린다.
--   그래서 서버가 이 플래그로 막는다 — 값이 있으면 409 ALREADY_ONBOARDED.
--
-- 왜 별도 플래그인가:
--   "부서가 하나라도 있으면 완료"로 판정하면, 부서를 전부 지운 회사가
--   온보딩을 다시 할 수 있게 된다. 온보딩 완료는 조직의 현재 상태가 아니라
--   지나간 사건이라 사건 자체를 기록한다.
--
--   GET /auth/me 의 isOnboarded 도 이 컬럼을 매번 읽는다. 토큰 클레임에 넣으면
--   온보딩을 끝내도 액세스 토큰 만료(30분)까지 온보딩 화면으로 되돌아간다.
-- =====================================================================

ALTER TABLE `company`
    ADD COLUMN `onboarded_at` DATETIME NULL
        COMMENT '온보딩 완료 시각. NULL 이면 미완료 — 값이 있으면 재요청을 409 로 막는다'
        AFTER `name`;
