-- =====================================================================
-- V2.3.21 : member.status ENUM 확장 (DELETED 추가)              [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   구성원 관리 화면에 "사원 삭제"(DELETE /api/manage/members/{id})가 생긴다.
--   물리 삭제는 하지 않는다 — 회의록·인수인계·감사 로그가 member 행을 참조하고
--   있어 지우면 그 이력이 통째로 끊긴다.
--
--   RESIGNED 를 재사용하지 않고 값을 새로 만드는 이유:
--   RESIGNED 는 "오프보딩 최종 승인"이라는 업무 절차를 통과했다는 감사 흔적이다
--   (V2.2.9·V2.2.12). 관리자가 목록에서 바로 지운 계정에 같은 값을 찍으면 그
--   절차를 밟은 퇴사자와 구분할 수 없게 되고, 인수인계 이력을 되짚을 때 "이 사람은
--   인계를 하고 나갔나"를 데이터로 답할 수 없다. 두 사건은 서로 다른 값이어야 한다.
--
-- 값 목록 (최종):
--   ACTIVE   재직 — 계정 발급 직후도 이 값이다
--   VACATION 휴직 — 휴직 최종 승인 후
--   WAITING  대기 — 휴직·오프보딩을 신청하고 승인을 기다리는 상태
--   RESIGNED 퇴사 — 오프보딩 최종 승인의 감사 흔적
--   DELETED  삭제 — 관리자의 사원 삭제(§7). 절차 없이 계정만 닫은 경우다
--
-- 주의:
--   ENUM 확장은 기존 행을 건드리지 않아 데이터 이관이 필요 없다. 되돌릴 때는 이
--   파일을 수정하지 않고 DELETED 를 빼는 새 마이그레이션을 만든다(운영 규칙 3·4) —
--   그때는 DELETED 행을 먼저 옮겨야 Error 1265 가 나지 않는다.
--
--   목록 제외 기준은 여전히 deleted_at 이다. 이 값은 "왜 닫혔는지"를 남길 뿐이고,
--   조회에서 거르는 일은 하지 않는다(V2.2.12 의 RESIGNED 와 같은 위치).
-- =====================================================================

ALTER TABLE `member`
    MODIFY COLUMN `status` ENUM('ACTIVE', 'VACATION', 'WAITING', 'RESIGNED', 'DELETED')
    NOT NULL DEFAULT 'ACTIVE'
    COMMENT 'ACTIVE=재직 / VACATION=휴직 / WAITING=대기 / RESIGNED=퇴사(오프보딩 승인) / DELETED=삭제(관리자)';
