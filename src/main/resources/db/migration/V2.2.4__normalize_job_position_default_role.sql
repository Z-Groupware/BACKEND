-- =====================================================================
-- V2.2.4 : job_position.default_role 의 OWNER/ADMIN 행 정리     [담당: 윤종호]
-- ---------------------------------------------------------------------
-- 배경:
--   직급↔권한 매핑에서 고를 수 있는 값은 LEADER / MEMBER 둘뿐으로 확정됐다.
--     · OWNER 를 허용하면 "직급으로 오너를 만드는" 우회 경로가 열린다.
--       오너는 기업 등록 시 1명만 생성되고 그 뒤로 늘어나지 않는다.
--     · ADMIN 은 직급 속성이 아니다. 직급에 매핑하면 그 직급인 사람 전원이
--       자동으로 어드민이 되는데, 어드민 부여 권한은 오너에게만 있다.
--
-- 주의:
--   ENUM 축소(V2.2.5)보다 먼저 실행돼야 한다 — 제거될 값이 행에 남아 있으면
--   MODIFY COLUMN 이 Error 1265 로 실패한다. 그래서 파일을 나눴다.
-- =====================================================================

UPDATE `job_position`
   SET `default_role` = 'MEMBER'
 WHERE `default_role` IN ('OWNER', 'ADMIN');
