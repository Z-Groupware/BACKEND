-- V4.7 : capture_upload_state에 누적 업로드 바이트 추가 (김현지 레인 V4.x)
-- ---------------------------------------------------------------------
-- cap → metering 저장 용량 미터링 연동(V4.5/V4.6에서 만든 플랫폼을 실제로 쓰기 시작)에 필요한
-- 값이다. 청크 완료 통보마다 이 값을 누적해 MeetingStorageUsage로 report한다.
--
-- segment_seq/last_seq와 달리 세그먼트 이어받기에도 리셋하지 않는다 — 이전 세그먼트 청크도
-- 지워지기 전까지는 여전히 스토리지를 차지하므로 회의 전체 누적값이어야 한다.
--
-- 기존 행이 없다는 전제로(이 연동이 지금까지 코드 자체가 없었음) NOT NULL DEFAULT 0으로 바로
-- 추가한다 — 나중에 채워야 할 기존 데이터가 없다.
-- =====================================================================

ALTER TABLE `capture_upload_state`
    ADD COLUMN `total_bytes_uploaded` BIGINT NOT NULL DEFAULT 0
        COMMENT '이 회의가 지금까지 업로드한 청크 총 바이트(세그먼트 무관 누적)' AFTER `last_block_end_offset_ms`;
