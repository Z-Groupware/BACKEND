-- =====================================================================
-- V5.18 : analysis_layer.heartbeat_at — 살아 있는 실행과 죽은 실행을 가른다 (#177)
-- ---------------------------------------------------------------------
-- 계층 잠금(status='RUNNING')은 중복 실행 방어의 실체인데, **잠근 프로세스가
-- 죽었는지를 몰랐다.** 배포나 크래시로 분석이 끊기면 그 행은 RUNNING 인 채로
-- 남고, 그 회의는 ANLZ-01 도 force 도 ANLZ-02 도 통과하지 못해 요약과 액션이
-- 영원히 만들어지지 않는다. 화면에는 「AI 처리 중」이 끝나지 않는다.
--
-- 회수 기준을 started_at 으로 잡을 수 없다. L5 는 tuple 수에 비례해 길어지므로
-- "시작한 지 N 분"으로 자르면 **살아서 돌고 있는 분석을 죽은 것으로 판정**해
-- 같은 회의를 두 번 태운다(토큰 두 배 + 두 실행이 서로 덮는 #134 상태).
--
-- 그래서 살아 있으면 갱신되는 값을 따로 둔다. 오케스트레이터가 계층을 잡을 때와
-- **모델 호출이 돌아올 때마다** 이 값을 찍으므로, 살아 있는 실행의 갱신 간격은
-- 초 단위다(ai.read-timeout=5s). 회수 유예를 분 단위로 잡아도 오탐이 나지 않는다.
--
-- NULL 을 허용하는 이유 — 이 마이그레이션 이전부터 RUNNING 이던 행이 있다.
-- 아래에서 started_at 으로 채우고, 읽는 쪽도 NULL 이면 started_at 을 본다.
-- =====================================================================

ALTER TABLE `analysis_layer`
    ADD COLUMN `heartbeat_at` DATETIME NULL
        COMMENT '이 계층을 잡은 실행이 마지막으로 살아 있던 시각. 멈춘 것만 회수한다(#177)'
        AFTER `started_at`;

-- 이미 남아 있는 RUNNING 행에 기준점을 준다. 이 값이 없으면 첫 회수 판정이
-- "기준 없음"으로 갈리고, 그 행들이 정확히 이 이슈가 말하는 갇힌 회의다.
UPDATE `analysis_layer`
   SET `heartbeat_at` = `started_at`
 WHERE `status` = 'RUNNING'
   AND `heartbeat_at` IS NULL;
