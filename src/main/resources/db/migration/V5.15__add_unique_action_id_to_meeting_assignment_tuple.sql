-- =====================================================================
-- V5.15 : meeting_assignment_tuple.action_id — tuple 하나당 action 하나
-- ---------------------------------------------------------------------
-- RVW-01 검토 조회가 action 과 이 테이블을 action_id 로 LEFT JOIN 한다. 그 조인이
-- 액션당 한 행이라는 것에 기대고 있는데, 지금은 그것을 보장하는 것이 아무것도 없다.
--
-- 두 tuple 이 같은 action 을 가리키면 조인이 액션을 여러 행으로 돌려주고, 검토 화면은
-- **같은 액션을 담당자 목록에 두 번 보여주며 검토 대상 건수도 두 번 센다.** 사람이
-- 없는 일을 확인하게 되고, 어느 쪽이 진짜인지 화면으로는 알 수 없다.
-- (CodeRabbit PR #150 지적)
--
-- ── 왜 UNIQUE 가 규칙인가 ────────────────────────────────────────────
-- 분배는 tuple 하나에서 액션 하나를 만든다. 반대(액션 하나가 tuple 여럿에서 나오는 것)는
-- 뜻이 성립하지 않는다 — tuple 은 "누가·무엇을·언제까지" 한 건이고, 그것이 곧 액션 한
-- 건이다. 여러 tuple 이 한 액션을 가리키는 상태는 규칙이 아니라 **분배 버그의 흔적**이다.
--
-- 그래서 화면에서 이상하게 보이기 전에 INSERT 에서 막는다. 응용 코드에도 같은 방어가
-- 있지만(엔티티가 이미 채워진 action_id 를 거절한다) 그것은 한 트랜잭션 안에서만 성립하고,
-- 동시에 두 실행이 들어오면 둘 다 통과한다.
--
-- ── NULL 이 여럿인 것은 정상이다 ─────────────────────────────────────
-- MySQL 의 UNIQUE 는 NULL 을 중복으로 보지 않는다. 아직 분배되지 않은 tuple 은 전부
-- action_id 가 NULL 이므로 한 회의에 몇 건이든 함께 있을 수 있다 — 이 제약이 막는 것은
-- "같은 액션을 가리키는 두 행"뿐이다.
--
-- 기존 인덱스가 이 일을 못 한다. V5.12 의 IX_ASSIGNMENT_TUPLE_PENDING 은
-- (meeting_id, action_id) 복합이라 유일성을 보장하지 않고, 선두 컬럼이 meeting_id 라서
-- RVW-01 의 조인(t.action_id = a.id)에도 쓰이지 않는다. 그 인덱스는 "이 회의의 미분배
-- 목록"을 읽는 용도이므로 그대로 둔다 — 묻는 것이 다르다.
-- =====================================================================

ALTER TABLE `meeting_assignment_tuple`
    ADD CONSTRAINT `UK_ASSIGNMENT_TUPLE_ACTION` UNIQUE (`action_id`);
