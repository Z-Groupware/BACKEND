package com.module06.backend.capture.domain.model;

/*
 * L1 이 화자를 그렇게 정한 근거다(transcript_chunk.speaker_source).
 *
 * 근거를 값으로 남기는 이유 — 두 경로의 신뢰도가 다르다. 본인 스트림의 음량이 가장 컸다는 것과
 * 나머지를 지우고 남았다는 것은 검증 방법이 다르고, 오귀속이 발견됐을 때 어느 경로를 조일지
 * 알아야 한다. 근거를 버리면 "화자가 틀렸다"만 남는다.
 *
 * ⚠ 이 enum 에 "미판정"을 두지 않는다. 판정 포기는 speaker_member_id 와 speaker_source 가
 * **함께 NULL** 인 것으로 표현한다(V5.3 주석). enum 값으로 만들면 "판정했는데 근거가 미판정"
 * 같은 모순된 조합이 저장될 수 있다.
 */
public enum SpeakerSource {

    /*
     * 본인 스트림의 rms 가 가장 컸다. 자막을 켠 참석자들 중 이 사람의 마이크가 그 구간에서
     * 가장 크게 잡혔다는 뜻이다 — 모델이 아니라 산수다.
     */
    SELF_STREAM,

    /*
     * 소거법. 참석자가 2명인 회의에서 한 명이 아니라고 판정되면 나머지 한 명이다.
     *
     * 참석자가 3명 이상이면 쓰지 않는다 — 한 명을 지워도 후보가 둘 남아 "나머지"가 정해지지
     * 않는다. 그때 억지로 하나를 고르면 그게 곧 오귀속이다.
     */
    ELIMINATION
}
