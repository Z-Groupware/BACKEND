package com.module06.backend.capture.domain.model;

/*
 * L6 규칙·모순 검사가 찾아내는 모순이다. **모델이 아니라 코드가 판정한다**
 * (명세 「L6 규칙·모순 검사 — Spring」).
 *
 * <h2>여기 있는 것과 없는 것</h2>
 * 전부 **데이터만 보고 확실히 말할 수 있는 것**이다. "이 배정이 적절한가" 같은 판단은
 * 없다 — 그건 L5 가 관점을 바꿔 묻는 일이고, 코드가 흉내내면 규칙이 계속 자란다.
 *
 * <h2>모순은 tuple 을 지우지 않는다</h2>
 * 표시만 하고 남긴다. 지우면 사람이 검토할 대상 자체가 사라지고, 무엇이 왜 걸렸는지도
 * 사라진다. 대신 L7 이 모순 있는 tuple 을 자동확정하지 않는다 — 게이트는 조이는
 * 방향으로만 쓴다.
 */
public enum ConflictType {

    /*
     * 같은 근거 발화에서 tuple 이 둘 이상 나왔다.
     *
     * 드문 사고가 아니라 **정상 동작의 부산물이다.** L2 는 주제 경계에 오버랩 3발화를
     * 얹어 돌려주고(경계 발화를 L3 가 양쪽에서 봐야 한다), L3·L4 는 주제마다 따로 돈다.
     * 그래서 오버랩 구간의 발화 하나가 두 주제에서 각각 항목이 되고 각각 tuple 이 될 수 있다.
     * (실호출 검증에서 오버랩이 실제로 발생하는 것을 확인했다.)
     *
     * 사람이 검토 화면에서 "이미 있는 것과 중복"으로 반려하는 것이 바로 이 모양이다.
     * 코드로 미리 잡을 수 있는 것을 사람에게 시키지 않는다.
     */
    DUPLICATE_EVIDENCE,

    /*
     * 기한이 회의 날짜보다 과거다.
     *
     * 회의에서 정한 일의 마감이 회의 이전일 수는 없다. 상대 표현("다음 주까지")을 절대
     * 날짜로 바꾸다 틀렸거나, 모델이 연도를 잘못 붙였을 때 나온다 — 그럴듯하게 틀린
     * 마감이 그대로 보드에 꽂히는 경로다.
     *
     * 회의 날짜를 모르면(meetingDate=null) 검사하지 않는다. 오늘 날짜로 대신 재면
     * 몇 주 뒤에 재실행했을 때 멀쩡한 기한이 전부 과거가 된다.
     */
    DUE_BEFORE_MEETING,

    /*
     * 담당자가 참석자 명단에 없다.
     *
     * 계층은 닫힌 목록에서만 고르므로 여기 걸리는 일은 없어야 한다. 그래도 검사하는 이유는
     * 명단이 조회 시점과 판정 시점 사이에 바뀔 수 있고(참석자 제외), 계약이 갈렸을 때
     * 조용히 통과하는 쪽으로 무너지지 않게 하기 위해서다.
     */
    ASSIGNEE_NOT_IN_ROSTER,

    /*
     * 1인칭 판정인데 근거 발화의 화자를 모른다.
     *
     * FIRST_PERSON 은 "제가 할게요"라고 **말한 사람**이 담당자라는 뜻이다. 그런데 그 발화의
     * speaker_member_id 가 NULL 이면 누가 말했는지 모르는 것이므로 **담당자 근거가 성립하지
     * 않는다.** 그런데도 담당자가 채워져 있다면 그 값은 다른 데서 온 추론이다.
     *
     * L1(화자 귀속)이 판정을 포기한 발화에서 나온다. CAP-11 이 붙기 전에는 자막이 0건이라
     * 전원 포기이므로, 지금은 1인칭 tuple 이 전부 여기 걸리는 것이 정상이다.
     */
    FIRST_PERSON_WITHOUT_SPEAKER,

    /*
     * 담당자 판정 근거는 있는데 담당자가 없다.
     *
     * assigneeSource 가 채워졌다는 것은 "어떻게 정했는지 안다"는 뜻인데 정해진 사람이 없다 —
     * 두 값이 서로를 부정한다. 한쪽이 잘못 채워진 것이므로 어느 쪽도 믿을 수 없다.
     */
    SOURCE_WITHOUT_ASSIGNEE
}
